import 'package:chartools_core/chartools_core.dart';
import 'package:test/test.dart';

/// A1 整串金样（p0-plan 人味增强包 A1 + #4 复核遗留 low）。
///
/// reply_prompt_test.dart 已按「contains / isNot(contains)」钉了默认路径的
/// 关键句，但不含句不等价于整串不变：两处句子对调、一个字词的替换都不惊动
/// 那组断言。这里把 systemPrompt(3) 的**默认输出完整钉死**——默认参数下
/// （follow / standard / 语域关 / 自然档 / 无场景 / usePositiveExamples 关）
/// 输出必须与 2026-11-11 的移植版逐字节一致，这是 A1 兼容锁的整串形态。
///
/// 金样是故意写死的大字面量：改提示词必须先改金样，让「文案变了」在评审里
/// 显式发生，而不是从 contains 断言的缝隙里溜过去。金样按 systemPrompt 的
/// 装配段分组，diff 时能直接定位到是哪一块变了。
void main() {
  // systemPrompt(3) 默认参数的完整输出。分段与 reply_prompt.dart 的装配一一
  // 对应：开场与 JSON 计数 → _strategyRule(3, natural) → 语气与自检段 →
  // _safetyBans（默认禁令式）→ _registerBans（语域关、无正向示范）→
  // _languageRule('follow') → _lengthRule('standard') → 收尾。
  // 已用脚本逐字节核对过（753 码元，2026-11-11）。
  const gold =
      // 开场 + JSON 计数（$n=3）
      '你是即时通讯回复助手，替用户起草能直接发出去的聊天回复。'
      '只输出一个 JSON 数组，含且仅含 3 个对象；每个对象必须有 strategy 和 text 两个字段。'
      // _strategyRule(3, 自然档)
      '策略必须固定且按顺序为：safe（稳妥承接）、forward（推进话题）、angle（换角度）；'
      '每种策略恰好一个对象，不能用随机采样制造差异。'
      // 语气贴氛围 + 敷衍承接 + 反模板 + 输出前自检
      '语气必须贴住这段对话真实的氛围和两人的亲密程度：对方在玩笑或打趣就轻松接住，不要突然煽情；'
      '对方在生气或施压就认真承接，不要插科打诨；对方只是日常闲聊就别上纲上线、别长篇大论。'
      '每条都必须直接回应对方最近一条消息，不要答非所问。'
      '对方只回一个字或明显敷衍时（「哦」「嗯」「嗯哪」「呵呵」「啊」「呃」这类），'
      '不要顺着上一轮继续加码，也不要重复追问同一个问题：先把话头递回去，'
      '确认对方现在是什么状态（怎么了 / 在想什么 / 还想不想继续），一句就够。'
      '各条的句式和节奏要彼此不同，不要像同一个模子刻出来的；'
      '像真人随手打字：不要连环下命令，不要每条都套「命令＋规矩＋下一步」的固定结构，'
      '也不要把对方刚说过的话原样扔回去纠正。'
      '输出前自检：哪一条读起来像模板、复读或客服腔，先改掉再输出。'
      // _safetyBans（默认：纯禁令式，A1 开关关闭）
      '硬性禁止（任何情况下都有效）：不要编造没发生过的事，不要提对方没提过的人和计划，'
      '不要写涉及未成年人的性或亲密内容，不要写非自愿、强迫、威胁或会真实伤害到人的内容，'
      '不要冒充他人，不要替用户许诺、转账或点链接。'
      // _registerBans（语域关 + 无正向示范）
      '另外禁止：不要角色扮演式台词，不要用「主人」「爸爸」「殿下」这类主仆或亲属式称呼，'
      '不要卑微求饶、自我贬低或过度道歉。'
      // _languageRule('follow')
      '回复语言跟随对方最近一条消息：对方用英文就用自然英文，对方用中文就用中文。'
      // _lengthRule('standard')
      '每条控制在 40 个中文字符以内或 30 个英文单词以内。'
      // 收尾
      '口语、自然、像真人在聊天软件里发消息。不要解释，直接输出 JSON 数组。';

  test('systemPrompt(3) 默认输出与金样逐字节一致', () {
    expect(ReplyPrompt.systemPrompt(3), gold);
  });

  test('金样路径确实受开关控制：打开 A1 正向示范输出即改变', () {
    // 默认路径有兼容锁的前提是开关真的在改东西——开关失效时金样会假绿。
    expect(ReplyPrompt.systemPrompt(3, usePositiveExamples: true),
        isNot(equals(gold)));
  });
}
